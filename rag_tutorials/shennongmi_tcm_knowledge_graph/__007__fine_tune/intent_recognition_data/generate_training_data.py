def tokenize_chinese(text: str) -> str:
    """
    使用 jieba 分词，将中文文本切分为空格分隔的词序列。

    fastText 模型要求输入文本为空格分隔的 token 序列，
    此函数在写入 fastText 数据文件时被调用，对每条文本
    进行中文分词预处理。

    参数:
        text: 原始中文文本（未分词）

    返回:
        str: 空格分隔的分词结果，如 "帮 我 写 一篇 小红书 笔记"
    """
    import jieba
    tokens = jieba.lcut(text)
    # 过滤掉纯空白 token，用空格连接
    return " ".join(t for t in tokens if t.strip())


def write_fasttext(filepath, samples):
    """
    将样本列表写入 fastText 格式的文本文件。

    fastText 格式要求:
        - 每行一条样本
        - 标签以 __label__ 开头，后跟空格分隔的分词文本
        - 示例: __label__发布 帮 我 写 一篇 小红书 笔记

    参数:
        filepath: 输出文件路径
        samples:  样本列表，格式为 [(label, text), ...]
                  其中 label 如 "__label__发布"、text 为原始中文文本
    """
    with open(filepath, "w", encoding="utf-8") as f:
        for label, text in samples:
            # 先分词再写入，确保训练/预测时的分词一致性
            f.write(f"{label} {tokenize_chinese(text)}\n")
    print(f"✅ FastText 已保存: {filepath} ({len(samples)} 条)")


def write_csv(filepath, samples):
    """
    将样本列表写入 CSV 文件（供 RoBERTa 训练使用）。

    CSV 格式:
        text,target
        枸杞有什么功效,是
        今天天气不错,否

    参数:
        filepath: 输出文件路径
        samples:  样本列表，格式为 [(label, text), ...]
                  其中 label 如 "是"/"否"
    """
    with open(filepath, "w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        # 写入表头
        writer.writerow(["text", "target"])
        for label, text in samples:
            writer.writerow([text, label])
    print(f"✅ CSV 已保存: {filepath} ({len(samples)} 条)")


def dedup_and_balance(samples, pos_label, neg_label, target_per_class, label_idx=0):
    """
    去重并平衡正负样本数量。

    核心逻辑:
        1. 去重: 以 (标签, 文本) 二元组为 key 去重，
           相同的标签+文本组合只保留一条
        2. 平衡: 如果某类样本超过目标数量，随机采样截断；
           如果不足目标数量，保持原样（不补齐，避免引入噪声）
        3. 打乱: 合并后随机 shuffle，避免相同类别的样本聚集

    参数:
        samples:          样本列表，元素格式取决于 label_idx
        pos_label:        正样本标签（如 "__label__发布" 或 "是"）
        neg_label:        负样本标签（如 "__label__非发布" 或 "否"）
        target_per_class: 每类样本的目标数量
        label_idx:        元素中标签的索引位置
                          0 = samples 格式为 (label, text)，如 FastText
                          1 = samples 格式为 (text, label)，如 RoBERTa CSV

    返回:
        list[(label, text)]: 去重、平衡、打乱后的样本列表
    """
    # 第一步：去重
    # 以 (label, text) 为 key，相同的组合只保留首次出现的
    seen = set()
    unique = []
    for item in samples:
        if label_idx == 0:
            # FastText 格式: item = (label, text)
            label, text = item[0], item[1]
        else:
            # RoBERTa 格式: item = (text, label)
            text, label = item[0], item[1]
        if (label, text) not in seen:
            seen.add((label, text))
            unique.append((label, text))  # 统一输出为 (label, text) 格式

    # 第二步：按标签分离正负样本
    pos = [(l, t) for l, t in unique if l == pos_label]
    neg = [(l, t) for l, t in unique if l == neg_label]

    # 第三步：截断多余样本（如果某类超过目标数量）
    if len(pos) > target_per_class:
        pos = random.sample(pos, target_per_class)
    if len(neg) > target_per_class:
        neg = random.sample(neg, target_per_class)

    # 第四步：合并并随机打乱
    result = pos + neg
    random.shuffle(result)

    print(f"  正({pos_label}): {len(pos)}  负({neg_label}): {len(neg)}  总计: {len(result)}")
    return result


def split_train_val(samples, val_ratio=0.2, seed=42):
    """
    将样本列表按分层比例拆分为训练集和验证集。

    分层策略:
        先按标签分离正负样本，分别在正/负样本内随机打乱后按比例拆分，
        然后将正负训练样本合并为训练集，正负验证样本合并为验证集。
        这种分层拆分确保训练集和验证集的正负比例与原始数据一致。

    参数:
        samples:    样本列表，格式为 [(label, text), ...]
                    其中 label 为 "__label__发布" 或 "__label__非发布"
        val_ratio:  验证集比例，默认 0.2（即 80% 训练 / 20% 验证）
        seed:       随机种子，保证拆分结果可复现

    返回:
        (train_samples, val_samples):
            - train_samples: 训练集样本列表 [(label, text), ...]
            - val_samples:   验证集样本列表 [(label, text), ...]
    """
    # 按标签分离正负样本
    pos = [(l, t) for l, t in samples if l == "__label__发布"]
    neg = [(l, t) for l, t in samples if l == "__label__非发布"]

    # 使用独立 Random 实例，避免影响全局随机状态
    rng = random.Random(seed)
    rng.shuffle(pos)
    rng.shuffle(neg)

    # 计算各集合的拆分点
    pos_split = int(len(pos) * (1 - val_ratio))  # 正样本训练集数量
    neg_split = int(len(neg) * (1 - val_ratio))  # 负样本训练集数量

    # 分配：前 N 条为训练集，剩余为验证集
    train = pos[:pos_split] + neg[:neg_split]
    val = pos[pos_split:] + neg[neg_split:]

    # 拆分后的集合内部打乱，避免同标签样本聚集
    rng.shuffle(train)
    rng.shuffle(val)

    print(f"  拆分: 训练集 {len(train)} 条, 验证集 {len(val)} 条")
    return train, val


def expand(text, prefixes=None, suffixes=None, n=1):
    """
    将一个文本扩展为 n 个变体（通过随机添加前后缀）。

    扩增策略:
        每次以 35% 的概率在文本前添加随机前缀（如 "请问，"),
        以 35% 的概率在文本后添加随机后缀（如 "？"、"。"），
        通过前缀和后缀的随机组合产生多样化的变体。

    去重机制:
        使用 seen 集合跟踪已生成的变体，确保同一个输入文本
        不会产生重复的输出变体。最多尝试 n * 10 次以防死循环。

    参数:
        text:     原始文本
        prefixes: 可选前缀列表，默认为常用中文对话前缀
        suffixes: 可选后缀列表，默认为常用中文标点和语气词
        n:        需要生成的变体数量

    返回:
        list[str]: n 个互不重复的文本变体
    """
    # 默认前缀列表：模拟用户不同的发问方式
    prefixes = prefixes or ["", "", "", "你好，", "请问，", "想问下，", "Hi，", "你好请问，"]
    # 默认后缀列表：模拟不同语气和标点习惯
    suffixes = suffixes or ["", "", "", "？", "。", "！", "~", "，谢谢"]
    results = []
    seen = set()
    attempts = 0
    # 最多尝试 n * 10 次，防止因前缀/后缀组合空间太小导致死循环
    while len(results) < n and attempts < n * 10:
        t = text
        # 35% 概率添加前缀
        if random.random() < 0.35:
            t = random.choice(prefixes) + t
        # 35% 概率添加后缀（添加前去除已有标点，避免重复）
        if random.random() < 0.35:
            t = t.rstrip("？。！~，") + random.choice(suffixes)
        attempts += 1
        # 去重：只有新的变体才加入结果
        if t not in seen:
            seen.add(t)
            results.append(t)
    return results


def product_expand(text, prefixes=None, suffixes=None):
    """
    确定性组合展开：每个 prefix x suffix 组合生成一个变体。

    与 expand() 的区别:
        - expand(): 随机抽样，每次运行结果不同（受 seed 影响）
        - product_expand(): 笛卡尔积，所有前缀 x 后缀组合都会生成，
          结果确定且不重复，适合需要大量唯一样本的场景

    参数:
        text:     原始文本
        prefixes: 可选前缀列表，默认 3 个前缀
        suffixes: 可选后缀列表，默认 4 个后缀

    返回:
        list[str]: len(prefixes) * len(suffixes) 个文本变体
    """
    # 默认前缀：覆盖不同礼貌程度
    prefixes = prefixes or ["", "请问，", "你好，请问，"]
    # 默认后缀：覆盖常见中文标点
    suffixes = suffixes or ["", "？", "。", "！"]
    results = []
    for p in prefixes:
        for s in suffixes:
            t = p + text
            # 去除原有末尾标点再添加新后缀，避免 "？。" 之类的双标点
            t = t.rstrip("？。！~，") + s
            results.append(t)
    return results


